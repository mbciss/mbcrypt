/* ==================================================================
 * Legacy XOR cipher
 * ================================================================== */

void mbcrypt_lib_xor(char *buf, size_t len)
{
    short k[] = { MBCRYPTKEY };
    const int klen = (int)(sizeof(k) / sizeof(k[0]));
    size_t i;
    short tmp;

    /* Deterministic key scramble — pairs regenerated by ./init_key */
    // start_rre
    tmp = k[13]; k[13] = k[12]; k[12] = tmp;
    tmp = k[9];  k[9]  = k[6];  k[6]  = tmp;
    tmp = k[7];  k[7]  = k[8];  k[8]  = tmp;
    tmp = k[1];  k[1]  = k[11]; k[11] = tmp;
    // end_rre

    for (i = 0; i < len; i++)
        buf[i] = (char)(k[(len - i) % klen] ^ (~(unsigned char)buf[i]));
}

/* ==================================================================
 * Zlib compression / decompression (heap only, no stack buffers)
 * ================================================================== */

char *mbcrypt_lib_zcompress(const char *in, size_t in_len, size_t *out_len)
{
    uLong bound;
    char *out;
    z_stream z;
    int ret;
    size_t written;

    *out_len = 0;
    if (!in || !in_len) return NULL;

    /* compressBound gives a safe upper bound — single allocation, no loop */
    bound = compressBound((uLong)in_len);
    out = (char *)malloc(bound);
    if (!out) return NULL;

    memset(&z, 0, sizeof(z));
    z.next_in   = (Bytef *)in;
    z.avail_in  = (uInt)in_len;
    z.next_out  = (Bytef *)out;
    z.avail_out = (uInt)bound;

    if (deflateInit(&z, Z_DEFAULT_COMPRESSION) != Z_OK) {
        free(out);
        return NULL;
    }
    ret     = deflate(&z, Z_FINISH);
    written = bound - (size_t)z.avail_out;
    deflateEnd(&z);

    if (ret != Z_STREAM_END) {
        free(out);
        return NULL;
    }

    /* Shrink to actual size (keep oversized buf if realloc fails) */
    {
        char *shrunk = (char *)realloc(out, written ? written : 1);
        if (shrunk) out = shrunk;
    }
    *out_len = written;
    return out;
}

char *mbcrypt_lib_zdecompress(const char *in, size_t in_len, size_t *out_len)
{
    z_stream z;
    int ret;
    size_t total = 0, avail;
    char *out, *chunk, *tmp;

    *out_len = 0;
    if (!in || !in_len) return NULL;

    chunk = (char *)malloc(ZLIB_CHUNK);
    avail = ZLIB_CHUNK * 4;
    out   = (char *)malloc(avail);
    if (!chunk || !out) {
        free(chunk);
        free(out);
        return NULL;
    }

    memset(&z, 0, sizeof(z));
    z.next_in  = (Bytef *)in;
    z.avail_in = (uInt)in_len;

    if (inflateInit(&z) != Z_OK) {
        free(chunk);
        free(out);
        return NULL;
    }

    do {
        size_t have;
        z.next_out  = (Bytef *)chunk;
        z.avail_out = ZLIB_CHUNK;

        ret = inflate(&z, Z_NO_FLUSH);
        if (ret == Z_STREAM_ERROR || ret == Z_DATA_ERROR ||
            ret == Z_MEM_ERROR    || ret == Z_NEED_DICT) {
            inflateEnd(&z);
            free(chunk);
            free(out);
            return NULL;
        }

        have = ZLIB_CHUNK - (size_t)z.avail_out;
        if (total + have > avail) {
            avail = (total + have) * 2;
            tmp = (char *)realloc(out, avail);
            if (!tmp) {
                inflateEnd(&z);
                free(chunk);
                free(out);
                return NULL;
            }
            out = tmp;
        }
        memcpy(out + total, chunk, have);
        total += have;
    } while (ret != Z_STREAM_END);

    inflateEnd(&z);
    free(chunk);

    /* Shrink to exact size */
    tmp = (char *)realloc(out, total ? total : 1);
    if (tmp) out = tmp;
    *out_len = total;
    return out;
}

/* ==================================================================
 * AES-256-GCM (OpenSSL EVP) — internal helpers
 * ================================================================== */

#ifdef MBCRYPT_HAS_OPENSSL

/* Derive a 256-bit key from password+salt using PBKDF2-SHA256 */
static int derive_key(const char *pass,
                       const uint8_t salt[MBCRYPT_PBKDF2_SALT_LEN],
                       uint8_t key[MBCRYPT_AES_KEY_LEN])
{
    return PKCS5_PBKDF2_HMAC(
        pass, (int)strlen(pass),
        salt, MBCRYPT_PBKDF2_SALT_LEN,
        MBCRYPT_PBKDF2_ITER,
        EVP_sha256(),
        MBCRYPT_AES_KEY_LEN, key) == 1 ? 0 : -1;
}

/* AES-256-GCM encrypt.
 * Fills caller-provided salt, iv, tag arrays.
 * Returns malloc'd ciphertext; *out_len = ciphertext length. */
static char *aes_gcm_encrypt(const char *in, size_t in_len,
                               size_t *out_len,
                               const char *password,
                               uint8_t salt[MBCRYPT_PBKDF2_SALT_LEN],
                               uint8_t iv  [MBCRYPT_AES_IV_LEN],
                               uint8_t tag [MBCRYPT_AES_TAG_LEN])
{
    uint8_t key[MBCRYPT_AES_KEY_LEN];
    EVP_CIPHER_CTX *ctx = NULL;
    char *out = NULL;
    int len = 0, flen = 0;

    *out_len = 0;

    if (RAND_bytes(salt, MBCRYPT_PBKDF2_SALT_LEN) != 1) return NULL;
    if (RAND_bytes(iv,   MBCRYPT_AES_IV_LEN)       != 1) return NULL;
    if (derive_key(password, salt, key)             != 0) return NULL;

    /* AES-GCM produces same-size output as input */
    out = (char *)malloc(in_len ? in_len : 1);
    if (!out) goto err;

    ctx = EVP_CIPHER_CTX_new();
    if (!ctx) goto err;

    if (EVP_EncryptInit_ex(ctx, EVP_aes_256_gcm(), NULL, NULL, NULL) != 1)
        goto err;
    if (EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_SET_IVLEN,
                             MBCRYPT_AES_IV_LEN, NULL)                != 1)
        goto err;
    if (EVP_EncryptInit_ex(ctx, NULL, NULL, key, iv)                  != 1)
        goto err;
    if (EVP_EncryptUpdate(ctx, (unsigned char *)out, &len,
                          (const unsigned char *)in, (int)in_len)     != 1)
        goto err;
    if (EVP_EncryptFinal_ex(ctx, (unsigned char *)out + len, &flen)   != 1)
        goto err;
    if (EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_GET_TAG,
                             MBCRYPT_AES_TAG_LEN, tag)                != 1)
        goto err;

    EVP_CIPHER_CTX_free(ctx);
    memset(key, 0, sizeof(key));
    *out_len = (size_t)(len + flen);
    return out;

err:
    EVP_CIPHER_CTX_free(ctx);
    free(out);
    memset(key, 0, sizeof(key));
    return NULL;
}

/* AES-256-GCM decrypt + authenticate.
 * Returns NULL if the GCM tag doesn't match (tampered data).
 * Returns malloc'd plaintext on success. */
static char *aes_gcm_decrypt(const char *in, size_t in_len,
                               size_t *out_len,
                               const char *password,
                               const uint8_t salt[MBCRYPT_PBKDF2_SALT_LEN],
                               const uint8_t iv  [MBCRYPT_AES_IV_LEN],
                               const uint8_t tag [MBCRYPT_AES_TAG_LEN])
{
    uint8_t key[MBCRYPT_AES_KEY_LEN];
    EVP_CIPHER_CTX *ctx = NULL;
    char *out = NULL;
    int len = 0, flen = 0, ret;

    *out_len = 0;
    if (derive_key(password, salt, key) != 0) return NULL;

    out = (char *)malloc(in_len ? in_len : 1);
    if (!out) goto err;

    ctx = EVP_CIPHER_CTX_new();
    if (!ctx) goto err;

    if (EVP_DecryptInit_ex(ctx, EVP_aes_256_gcm(), NULL, NULL, NULL) != 1)
        goto err;
    if (EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_SET_IVLEN,
                             MBCRYPT_AES_IV_LEN, NULL)                != 1)
        goto err;
    if (EVP_DecryptInit_ex(ctx, NULL, NULL, key, iv)                  != 1)
        goto err;
    if (EVP_DecryptUpdate(ctx, (unsigned char *)out, &len,
                          (const unsigned char *)in, (int)in_len)     != 1)
        goto err;
    /* Set expected tag BEFORE calling Final */
    if (EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_SET_TAG,
                             MBCRYPT_AES_TAG_LEN, (void *)tag)        != 1)
        goto err;

    /* Final verifies the GCM tag — returns <= 0 on auth failure */
    ret = EVP_DecryptFinal_ex(ctx, (unsigned char *)out + len, &flen);
    EVP_CIPHER_CTX_free(ctx);
    memset(key, 0, sizeof(key));

    if (ret <= 0) {
        /* Authentication failure — data tampered or wrong password */
        free(out);
        return NULL;
    }

    *out_len = (size_t)(len + flen);
    return out;

err:
    EVP_CIPHER_CTX_free(ctx);
    free(out);
    memset(key, 0, sizeof(key));
    return NULL;
}

#endif /* MBCRYPT_HAS_OPENSSL */

/* ==================================================================
 * Detect
 * ================================================================== */

int mbcrypt_lib_detect(const char *blob, size_t blob_len)
{
    if (!blob || blob_len < MBCRYPTTAG_LEN) return MBCRYPT_NOT_ENCRYPTED;

    if (memcmp(blob, MBCRYPTTAG_V3_STR, MBCRYPTTAG_LEN) == 0) {
        if (blob_len >= MBCRYPT_V3_BASE_LEN) {
            const mbcrypt_v3_header_t *h = (const mbcrypt_v3_header_t *)blob;
            return (int)h->method;
        }
        return MBCRYPT_LEGACY_MODE; /* V3 tag but truncated header */
    }

    if (memcmp(blob, MBCRYPTTAG_V2_STR, MBCRYPTTAG_LEN) == 0)
        return MBCRYPT_LEGACY_MODE; /* V2 is always legacy XOR */

    return MBCRYPT_NOT_ENCRYPTED;
}

/* ==================================================================
 * High-level encode
 * ================================================================== */

char *mbcrypt_lib_encode(const char *src, size_t src_len, size_t *out_len,
                          int mode, const char *password)
{
    char *compressed = NULL, *ciphertext = NULL, *blob = NULL;
    size_t compressed_len = 0, cipher_len = 0, blob_len = 0;
    mbcrypt_v3_header_t *hdr;

    *out_len = 0;
    if (!src || !src_len) return NULL;

    /* Step 1: compress */
    compressed = mbcrypt_lib_zcompress(src, src_len, &compressed_len);
    if (!compressed || !compressed_len) goto fail;

#ifdef MBCRYPT_HAS_OPENSSL
    if (mode == MBCRYPT_AES_GCM_MODE && password && *password) {
        uint8_t salt[MBCRYPT_PBKDF2_SALT_LEN];
        uint8_t iv  [MBCRYPT_AES_IV_LEN];
        uint8_t tag [MBCRYPT_AES_TAG_LEN];

        /* Step 2a: AES-256-GCM encrypt */
        ciphertext = aes_gcm_encrypt(compressed, compressed_len, &cipher_len,
                                      password, salt, iv, tag);
        free(compressed); compressed = NULL;
        if (!ciphertext) goto fail;

        /* Step 3a: build V3 AES blob */
        blob_len = MBCRYPT_V3_AES_LEN + cipher_len;
        blob = (char *)malloc(blob_len);
        if (!blob) goto fail;

        hdr = (mbcrypt_v3_header_t *)blob;
        memcpy(hdr->tag, MBCRYPTTAG_V3_STR, MBCRYPTTAG_LEN);
        hdr->version = 3;
        hdr->method  = MBCRYPT_AES_GCM_MODE;
        memset(hdr->reserved, 0, sizeof(hdr->reserved));

        {
            uint8_t *p = (uint8_t *)(blob + MBCRYPT_V3_BASE_LEN);
            memcpy(p, salt, MBCRYPT_PBKDF2_SALT_LEN); p += MBCRYPT_PBKDF2_SALT_LEN;
            memcpy(p, iv,   MBCRYPT_AES_IV_LEN);       p += MBCRYPT_AES_IV_LEN;
            memcpy(p, tag,  MBCRYPT_AES_TAG_LEN);       p += MBCRYPT_AES_TAG_LEN;
            memcpy(p, ciphertext, cipher_len);
        }

        free(ciphertext);
        *out_len = blob_len;
        return blob;
    }
#endif

    /* Step 2b: legacy XOR (in-place) */
    mbcrypt_lib_xor(compressed, compressed_len);

    /* Step 3b: build V3 legacy blob */
    blob_len = MBCRYPT_V3_BASE_LEN + compressed_len;
    blob = (char *)malloc(blob_len);
    if (!blob) goto fail;

    hdr = (mbcrypt_v3_header_t *)blob;
    memcpy(hdr->tag, MBCRYPTTAG_V3_STR, MBCRYPTTAG_LEN);
    hdr->version = 3;
    hdr->method  = MBCRYPT_LEGACY_MODE;
    memset(hdr->reserved, 0, sizeof(hdr->reserved));
    memcpy(blob + MBCRYPT_V3_BASE_LEN, compressed, compressed_len);

    free(compressed);
    *out_len = blob_len;
    return blob;

fail:
    free(compressed);
    free(ciphertext);
    free(blob);
    return NULL;
}

/* ==================================================================
 * High-level decode  (V2 and V3 formats)
 * ================================================================== */

char *mbcrypt_lib_decode(const char *blob, size_t blob_len, size_t *out_len,
                          const char *password)
{
    int method;
    char *tmp = NULL, *plain = NULL;
    size_t tmp_len = 0, plain_len = 0;

    *out_len = 0;

    method = mbcrypt_lib_detect(blob, blob_len);
    if (method == MBCRYPT_NOT_ENCRYPTED) return NULL;

    /* ---- V2 legacy format (tag only, then XOR data) ---- */
    if (memcmp(blob, MBCRYPTTAG_V2_STR, MBCRYPTTAG_LEN) == 0) {
        const char *data = blob + MBCRYPTTAG_LEN;
        size_t dlen = blob_len - MBCRYPTTAG_LEN;

        tmp = (char *)malloc(dlen);
        if (!tmp) return NULL;
        memcpy(tmp, data, dlen);
        tmp_len = dlen;
        mbcrypt_lib_xor(tmp, tmp_len);
        plain = mbcrypt_lib_zdecompress(tmp, tmp_len, &plain_len);
        free(tmp);
        *out_len = plain_len;
        return plain;
    }

    /* ---- V3 format ---- */
    if (blob_len < MBCRYPT_V3_BASE_LEN) return NULL;

    if (method == MBCRYPT_AES_GCM_MODE) {
#ifdef MBCRYPT_HAS_OPENSSL
        if (!password || !*password) return NULL;
        if (blob_len < MBCRYPT_V3_AES_LEN) return NULL;

        {
            const uint8_t *p    = (const uint8_t *)(blob + MBCRYPT_V3_BASE_LEN);
            const uint8_t *salt = p; p += MBCRYPT_PBKDF2_SALT_LEN;
            const uint8_t *iv   = p; p += MBCRYPT_AES_IV_LEN;
            const uint8_t *tag  = p; p += MBCRYPT_AES_TAG_LEN;
            const char    *data = (const char *)p;
            size_t         dlen = blob_len - MBCRYPT_V3_AES_LEN;

            tmp = aes_gcm_decrypt(data, dlen, &tmp_len,
                                   password, salt, iv, tag);
            if (!tmp) return NULL; /* Auth failure or wrong password */

            plain = mbcrypt_lib_zdecompress(tmp, tmp_len, &plain_len);
            free(tmp);
        }
        *out_len = plain_len;
        return plain;
#else
        return NULL; /* OpenSSL unavailable at compile time */
#endif
    }

    /* V3 legacy XOR */
    {
        const char *data = blob + MBCRYPT_V3_BASE_LEN;
        size_t dlen = blob_len - MBCRYPT_V3_BASE_LEN;

        tmp = (char *)malloc(dlen);
        if (!tmp) return NULL;
        memcpy(tmp, data, dlen);
        tmp_len = dlen;
        mbcrypt_lib_xor(tmp, tmp_len);
        plain = mbcrypt_lib_zdecompress(tmp, tmp_len, &plain_len);
        free(tmp);
    }
    *out_len = plain_len;
    return plain;
}
